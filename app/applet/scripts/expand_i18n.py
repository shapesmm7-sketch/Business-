i18n_path = '/app/applet/src/utils/i18n.ts'
with open(i18n_path, 'r', encoding='utf-8') as f:
    content = f.read()

# For each language in EXTENSIONS, we inject the keys right before the end of that language object
for lang_code, keys_dict in EXTENSIONS.items():
    # Find the language block: e.g. "  en: {\n" up to the matching "  },\n"
    # Regex to find: lang_code: { ... },
    pattern = rf"(\b{lang_code}:\s*\{{)([\s\S]*?)(\n  \}},)"
    match = re.search(pattern, content)
    if not match:
        print(f"Could not find block for {lang_code}")
        continue
    
    header = match.group(1)
    body = match.group(2)
    footer = match.group(3)
    
    # Format the new entries
    lines = []
    for k, v in keys_dict.items():
        # Only add if key doesn't already exist in body
        if f"{k}:" not in body:
            # Escape single quotes in v if any
            v_escaped = v.replace("'", "\\'")
            lines.append(f"    {k}: '{v_escaped}',")
    
    if lines:
        new_body = body + "\n" + "\n".join(lines)
        new_block = header + new_body + footer
        content = content[:match.start()] + new_block + content[match.end():]
        print(f"Added {len(lines)} keys to {lang_code}")

with open(i18n_path, 'w', encoding='utf-8') as f:
    f.write(content)

