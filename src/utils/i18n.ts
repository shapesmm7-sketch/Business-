/**
 * Gets translation for a given key in the user's active language.
 * Uses English fallback if string is missing in chosen target language.
 */
export function t(key: string, targetLangNameOrCode?: string): string {
  if (!targetLangNameOrCode && typeof window !== 'undefined') {
    try {
      const storedProfile = localStorage.getItem('brivu_business_profile');
      if (storedProfile) {
        const parsed = JSON.parse(storedProfile);
        targetLangNameOrCode = parsed.language;
      }
    } catch {
      // ignore
    }
  }

  const langObj = getLanguageByCode(targetLangNameOrCode || 'en');
  const code = langObj.code.toLowerCase();

  // 1. Direct match in dictionary
  if (TRANSLATIONS[code] && TRANSLATIONS[code][key]) {
    return TRANSLATIONS[code][key];
  }

  // 2. Base 2-letter language code match (e.g. 'zh-TW' -> 'zh')
  const baseCode = code.split('-')[0];
  if (TRANSLATIONS[baseCode] && TRANSLATIONS[baseCode][key]) {
    return TRANSLATIONS[baseCode][key];
  }

  // 3. Fallback to English
  if (TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }

  // 4. Fallback to key itself formatted gracefully
  return key.replace(/_/g, ' ').replace(/\b\w/g, (l) => l.toUpperCase());
}
